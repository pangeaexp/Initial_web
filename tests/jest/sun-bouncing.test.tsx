test('a completed round enters the top five, survives reload, and a weaker round is not ranked', () => {
  const saved = [20, 15, 10, 5, 1].map((points) => ({ id: `seed-${points}`, points, hits: points, misses: 0, bestStreak: points }))
  localStorage.setItem(LEADERBOARD_KEY, JSON.stringify(saved))
  const view = mount()
  start()
  catchBall()
  catchBall()
  expect(JSON.parse(localStorage.getItem(LEADERBOARD_KEY)!)).toHaveLength(5)
  act(() => jest.advanceTimersByTime(30_100))
  expect(screen.getByText('Puesto 5 en tu clasificación')).toBeInTheDocument()
  const ranking = screen.getByRole('region', { name: 'Tus 5 mejores partidas' })
  expect(within(ranking).getAllByRole('listitem')).toHaveLength(5)
  expect(within(ranking).getByText('Esta partida').closest('li')).toHaveAttribute('aria-current', 'true')
  const entries = JSON.parse(localStorage.getItem(LEADERBOARD_KEY)!) as { points: number }[]
  expect(entries.map((entry) => entry.points)).toEqual([20, 15, 10, 5, 2])
  view.unmount()
  mount()
  start()
  act(() => jest.advanceTimersByTime(30_100))
  expect(screen.getByText('Esta partida no entra en tus cinco mejores.')).toBeInTheDocument()
  expect(screen.queryByText('Esta partida')).not.toBeInTheDocument()
  expect(JSON.parse(localStorage.getItem(LEADERBOARD_KEY)!)).toEqual(entries)
})


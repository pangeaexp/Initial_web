/// <reference types="jest" />

import { act, cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import '@testing-library/jest-dom'
import SunBouncing from '@/components/SunBouncing'
import { TranslationProvider } from '@/lib/i18n'
import dictionary from '@/lib/i18n/locales/es.json'
import { ACHIEVEMENTS_KEY } from '@/lib/sun-game-achievements'
import { LEADERBOARD_KEY } from '@/lib/sun-game-leaderboard'

const recordKey = 'cejoventut.sun-game.best.v1'
const mount = () => render(
  <TranslationProvider initialLanguage="es" dictionary={dictionary}>
    <SunBouncing />
  </TranslationProvider>,
)
const start = () => fireEvent.click(screen.getByRole('button', { name: 'Jugar' }))
const catchBall = () => fireEvent.click(screen.getByRole('button', { name: 'Atrapar la pelota' }))

// jsdom does not provide PointerEvent; MouseEvent exposes the button field here.
beforeAll(() => { window.PointerEvent = MouseEvent as typeof PointerEvent })

beforeEach(() => {
  jest.useFakeTimers()
  localStorage.clear()
  Object.defineProperty(HTMLDialogElement.prototype, 'showModal', {
    configurable: true,
    value: function (this: HTMLDialogElement) { this.setAttribute('open', '') },
  })
  Object.defineProperty(HTMLDialogElement.prototype, 'close', {
    configurable: true,
    value: function (this: HTMLDialogElement) { this.removeAttribute('open') },
  })
  jest.spyOn(HTMLMediaElement.prototype, 'play').mockResolvedValue()
  jest.spyOn(HTMLMediaElement.prototype, 'pause').mockImplementation(() => {})
})

afterEach(() => {
  cleanup()
  jest.useRealTimers()
  jest.restoreAllMocks()
})

